"""Original geometric single-line Japanese subset, drawn on a 0..24 grid.

These coordinates are authored for this project, not traced from ChocoKanji
or another font. Shared radicals keep the small display's stroke spacing even.
No curves, outlines, erosion, or third-party font dependency are needed.
"""


import unicodedata

def strokes(value):
    return [[tuple(map(float, point.split(','))) for point in line.split()]
            for line in value.split(';') if line.strip()]


def fit(glyph, x, y, width, height):
    return [[(x + a*width/24, y + b*height/24) for a, b in line] for line in glyph]


G = {}
R = {}


def add(char, value):
    G[char] = strokes(value)
    return G[char]


def parts(char, *items):
    G[char] = [line for glyph, box in items for line in fit(glyph, *box)]
    return G[char]


